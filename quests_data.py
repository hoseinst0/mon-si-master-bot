HIDDEN_QUESTS = ["c1_hidden", "c2_hidden", "c3_hidden1", "c3_hidden2"]


def get_quest(qid):
    return QUESTS.get(qid)


def next_main_quest(player_doc):
    """کوئست اصلی بعدی که بازیکن هنوز انجام نداده و پیش‌نیازهایش کامل شده."""
    done = set(player_doc.get("quests_completed", []))
    for qid in MAIN_LINE_ORDER:
        if qid in done:
            continue
        q = QUESTS[qid]
        if all(p in done for p in q.get("prereq", [])):
            return q
        return None  # پیش‌نیاز کامل نشده، صبر کن
    return None  # همه‌چیز تمام شده


def available_hidden_quests(player_doc):
    done = set(player_doc.get("quests_completed", []))
    out = []
    for qid in HIDDEN_QUESTS:
        if qid in done:
            continue
        q = QUESTS[qid]
        if all(p in done for p in q.get("prereq", [])):
            out.append(q)
    return out
