def get_event(event_id: str) -> dict | None:
    return DARK_EVENTS.get(event_id)


def get_option(event_id: str, option_key: str) -> dict | None:
    ev = get_event(event_id)
    if not ev:
        return None
    for opt in ev["options"]:
        if opt["key"] == option_key:
            return opt
    return None


def resolve_dice_outcome(option: dict, dice_value: int):
    for (lo, hi), text, effects in option["outcomes"]:
        if lo <= dice_value <= hi:
            return text, effects
    return option["outcomes"][-1][1], option["outcomes"][-1][2]
